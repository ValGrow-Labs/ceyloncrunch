function makeVariants(prefix: string, p100: number, p250: number, p500: number, p1k: number): ProductVariant[] {
  return [
    { id: `${prefix}-100g`, weight: '100g', price: p100, originalPrice: Math.round(p100 * 1.15), stock: 25 },
    { id: `${prefix}-250g`, weight: '250g', price: p250, originalPrice: Math.round(p250 * 1.15), stock: 20 },
    { id: `${prefix}-500g`, weight: '500g', price: p500, originalPrice: Math.round(p500 * 1.12), stock: 15 },
    { id: `${prefix}-1kg`, weight: '1kg', price: p1k, originalPrice: Math.round(p1k * 1.1), stock: 10 },
  ];
}

