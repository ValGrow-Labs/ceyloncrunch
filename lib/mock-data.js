export function isDevBypass() {
  if (process.env.ADMIN_BYPASS === 'true') return true
  if (process.env.ADMIN_BYPASS === 'false') return false
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL || ''
  return !url || url.includes('your-project-id')
}

